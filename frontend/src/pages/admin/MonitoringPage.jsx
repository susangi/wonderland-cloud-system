import { useEffect, useState } from 'react';
import { BarChart3, ExternalLink } from 'lucide-react';
import KpiCard from '../../components/KpiCard';
import EmptyState from '../../components/EmptyState';
import Alert, { ErrorAlert } from '../../components/Alert';
import { getAnalyticsSummary } from '../../api/eventApi';
import { addDays, formatCount, formatMoney, parkToday } from '../../utils/format';
import { METABASE_URL } from '../../utils/config';
import { ActivityByHourChart, TicketsByTierChart, TopRidesChart, VisitorsPerDayChart } from './MonitoringCharts';

// Admin monitoring view (design/Screens.md section 8, FR-A-08 to FR-A-11, FR-A-13).
// Full dashboards are in Metabase; this page shows the key numbers and simple charts.

const PRESETS = [
  { label: 'Today', days: 1 },
  { label: '7 days', days: 7 },
  { label: '30 days', days: 30 },
];

export default function MonitoringPage() {
  const today = parkToday();
  const [range, setRange] = useState({ from: addDays(today, -29), to: today });
  const [summary, setSummary] = useState(null);
  const [visitorsToday, setVisitorsToday] = useState(null);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState(null);

  function loadSummary() {
    setIsLoading(true);
    setError(null);
    getAnalyticsSummary(range.from, range.to)
      .then(setSummary)
      .catch(setError)
      .finally(() => setIsLoading(false));

    // "Visitors today" is always today, whatever range is chosen.
    getAnalyticsSummary(today, today)
      .then((todaySummary) => setVisitorsToday(todaySummary.totals.visitors))
      .catch(() => setVisitorsToday(null));
  }

  useEffect(loadSummary, [range.from, range.to]);

  function applyPreset(days) {
    setRange({ from: addDays(today, -(days - 1)), to: today });
  }

  const hasData = summary && (summary.totals.tickets > 0 || summary.totals.visitors > 0 || summary.top_rides.length > 0);
  const topRide = summary?.top_rides[0];

  return (
    <div className="wl-stack">
      <div className="wl-page-head">
        <h1>Monitoring</h1>
        <div className="wl-range">
          <DateInput id="range-from" label="From" value={range.from} max={range.to} onChange={(from) => setRange({ ...range, from })} />
          <DateInput id="range-to" label="To" value={range.to} min={range.from} onChange={(to) => setRange({ ...range, to })} />
          {PRESETS.map((preset) => (
            <button key={preset.label} type="button" className="wl-chip" aria-pressed={range.from === addDays(today, -(preset.days - 1)) && range.to === today} onClick={() => applyPreset(preset.days)}>
              {preset.label}
            </button>
          ))}
          {METABASE_URL && (
            <a className="wl-btn" href={METABASE_URL} target="_blank" rel="noreferrer" title="Needs the port-forward running">
              <ExternalLink aria-hidden="true" />
              Open Metabase dashboard
            </a>
          )}
        </div>
      </div>

      {error && <ErrorAlert error={error} onRetry={loadSummary} />}

      <div className="wl-kpis">
        <KpiCard label="Visitors today" value={formatCount(visitorsToday ?? 0)} isLoading={isLoading} />
        <KpiCard label="Tickets sold" value={formatCount(summary?.totals.tickets)} isLoading={isLoading} />
        <KpiCard label="Revenue" value={formatMoney(summary?.totals.revenue, 'USD', { decimals: 0 })} isLoading={isLoading} />
        <KpiCard label="Top ride" value={topRide?.attraction_name || '–'} note={topRide && `${formatCount(topRide.uses)} rides in this range`} isLoading={isLoading} />
      </div>

      {summary?.includes_simulated && <Alert variant="info" title="Includes sample data generated by the simulator." />}

      {isLoading && (
        <div className="wl-charts" aria-busy="true">
          {[1, 2, 3, 4].map((key) => <div key={key} className="wl-card wl-skeleton" style={{ height: 300 }} aria-hidden="true" />)}
        </div>
      )}

      {!isLoading && !error && !hasData && (
        <EmptyState
          icon={BarChart3}
          title="No activity in this date range"
          text="Try a longer range."
          action={<button type="button" className="wl-btn wl-btn--primary" onClick={() => applyPreset(30)}>Last 30 days</button>}
        />
      )}

      {!isLoading && !error && hasData && (
        <div className="wl-charts">
          <VisitorsPerDayChart data={summary.visitors_per_day} />
          <TicketsByTierChart data={summary.tickets_by_tier} />
          <TopRidesChart data={summary.top_rides} />
          <ActivityByHourChart data={summary.activity_by_hour} />
        </div>
      )}
    </div>
  );
}

function DateInput({ id, label, value, onChange, min, max }) {
  return (
    <div className="wl-field">
      <label className="wl-label" htmlFor={id}>{label}</label>
      <input id={id} type="date" className="wl-input" value={value} min={min} max={max} onChange={(event) => event.target.value && onChange(event.target.value)} />
    </div>
  );
}
