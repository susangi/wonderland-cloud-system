<?php

namespace App\Services;

use App\Repositories\ParkEventRepository;
use App\Traits\UsesParkTime;
use Carbon\CarbonImmutable;

// Numbers for the admin monitoring view (design 6.5, FR-A-08 to FR-A-11, FR-A-13).
class AnalyticsService
{
    use UsesParkTime;

    // Without dates the view shows the last 30 park days, including today.
    private const DEFAULT_DAYS = 30;

    public function __construct(private ParkEventRepository $parkEventRepository) {}

    public function summary(?string $fromParkDate, ?string $toParkDate): array
    {
        $toParkDate ??= $this->parkToday();
        $fromParkDate ??= CarbonImmutable::parse($toParkDate)->subDays(self::DEFAULT_DAYS - 1)->toDateString();

        [$fromUtc, $toUtc] = $this->parkDaysToUtcRange($fromParkDate, $toParkDate);

        return [
            'range' => ['from' => $fromParkDate, 'to' => $toParkDate],
            'visitors_per_day' => $this->parkEventRepository->visitorsPerDay($fromUtc, $toUtc),
            'tickets_by_tier' => $this->parkEventRepository->ticketsByTier($fromUtc, $toUtc),
            'top_rides' => $this->parkEventRepository->topRides($fromUtc, $toUtc),
            'activity_by_hour' => $this->parkEventRepository->activityByHour($fromUtc, $toUtc),
            'totals' => $this->parkEventRepository->totals($fromUtc, $toUtc),
            // The admin view then shows "Includes sample data generated by the simulator."
            'includes_simulated' => $this->parkEventRepository->hasSimulatedRows($fromUtc, $toUtc),
        ];
    }
}
